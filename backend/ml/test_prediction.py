"""
Phase 7C -- Test Prediction Script (Development Only)

Loads the Phase 7C model (backend/ml/model/disease_model.joblib) and runs
several realistic symptom combinations against it.

Input symptom names must exactly match the canonical feature names in
symptom_columns.joblib (e.g. 'symptom_fever'). Any symptom that is NOT in the
feature set is reported, never silently ignored.

IMPORTANT (academic decision-support):
- The raw score is the fraction of Random Forest trees voting for a class. It
  is NOT a calibrated or medically validated probability.
- Predictions are NOT a medical diagnosis.
"""

import os
import sys
import time

import numpy as np
import joblib

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODEL_DIR = os.path.join(BASE_DIR, "ml", "model")
MODEL_PATH = os.path.join(MODEL_DIR, "disease_model.joblib")
SYMPTOMS_PATH = os.path.join(MODEL_DIR, "symptom_columns.joblib")

TOP_N = 5

# Realistic symptom combinations. Every symptom below must exist in the
# dataset feature set (verified against symptom_columns.joblib).
TEST_CASES = [
    ("fever + cough", ["symptom_fever", "symptom_cough"]),
    ("fever + headache", ["symptom_fever", "symptom_headache"]),
    ("fever + vomiting", ["symptom_fever", "symptom_vomiting"]),
    (
        "cough + sore throat + nasal congestion",
        ["symptom_cough", "symptom_sore_throat", "symptom_nasal_congestion"],
    ),
    (
        "headache + nausea + vomiting",
        ["symptom_headache", "symptom_nausea", "symptom_vomiting"],
    ),
]


def main():
    print()
    print("=" * 60)
    print("  PHASE 7C -- DEVELOPMENT TEST PREDICTIONS")
    print("  (Not a medical diagnosis)")
    print("=" * 60)
    print()

    if not os.path.exists(MODEL_PATH) or not os.path.exists(SYMPTOMS_PATH):
        print("ERROR: Model or symptom metadata missing.")
        print("Run train.py first.")
        sys.exit(1)

    # --- Load model --------------------------------------------------------
    t0 = time.time()
    clf = joblib.load(MODEL_PATH)
    load_s = time.time() - t0
    symptom_cols = joblib.load(SYMPTOMS_PATH)
    print(f"  Model loaded:      {MODEL_PATH}")
    print(f"  Load time:         {load_s:.2f}s")
    print(f"  Symptom features:  {len(symptom_cols)}")
    print(f"  Model n_features:  {getattr(clf, 'n_features_in_', '?')}")
    print(f"  Model classes:     {len(clf.classes_)}")
    print()

    for label, symptoms in TEST_CASES:
        print("=" * 60)
        print(f"  CASE: {label}")
        print("=" * 60)

        # --- Validate every input symptom exists ---------------------------
        invalid = [s for s in symptoms if s not in symptom_cols]
        if invalid:
            print("  ERROR: The following input symptoms do NOT exist in the")
            print("  model feature set and were NOT ignored:")
            for s in invalid:
                print(f"    X {s}")
            print("  (Skipping this case; no prediction run.)")
            print()
            continue

        valid = [s for s in symptoms if s in symptom_cols]
        print("  Input symptoms (all validated against the model):")
        for s in valid:
            print(f"    OK {s}")

        # --- Build feature vector in exact training order ------------------
        vector = np.zeros(len(symptom_cols), dtype=np.int8)
        for s in valid:
            vector[symptom_cols.index(s)] = 1
        X_input = vector.reshape(1, -1)
        print(f"  Active features: {int(vector.sum())} / {len(symptom_cols)}")

        # --- Predict -------------------------------------------------------
        t1 = time.time()
        proba = clf.predict_proba(X_input)[0]
        inference_s = (time.time() - t1) * 1000.0
        classes = clf.classes_

        order = np.argsort(proba)[::-1][:TOP_N]
        print(f"  Inference time:  {inference_s:.1f} ms")
        print()
        print("  TOP 5 PREDICTIONS (raw Random Forest scores, NOT")
        print("  calibrated probabilities and NOT a diagnosis):")
        print("  " + "-" * 52)
        for rank, idx in enumerate(order, 1):
            disease = classes[idx]
            score = proba[idx]
            print(f"    {rank}. {disease:<46s} {score:.4f}")
        print()

    print("  DISCLAIMER: These are development test predictions generated by")
    print("  a machine learning model. Raw scores are NOT calibrated or")
    print("  medically validated probabilities. They are NOT a medical")
    print("  diagnosis. Consult a qualified healthcare professional for any")
    print("  medical concerns.")
    print()


if __name__ == "__main__":
    main()